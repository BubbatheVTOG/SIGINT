#!/usr/bin/env bash
# Theme Toggle Script — cycles 7 themes by generating palette files into
# ~/.config/theme/ (a gitignored real directory, not stowed).
#
# Affected: Hyprland borders, Waybar CSS, Kitty, Rofi, Tmux, Hyprpaper
#           wallpaper, Hyprlock, Fastfetch palette.
#
# Cycle: teal → red → green → yellow → orange → purple → white → teal → ...
# State: ~/.cache/current_theme (theme name string).
#
# --init: apply the current theme without cycling (bootstrap on first boot).
#
# All color values are defined in indexed arrays below — one entry per theme
# in cycle order.  Adding a theme = append one element to every array + drop a
# matching <name>.jpg into ~/.config/hypr/wallpapers/.

THEME_FILE="$HOME/.cache/current_theme"
PALETTE_DIR="$HOME/.config/theme"

# --- Theme cycle order (index = position in this list) ---
THEMES=(teal red green yellow orange purple white)
declare -A IDX=( [teal]=0 [red]=1 [green]=2 [yellow]=3 [orange]=4 [purple]=5 [white]=6 )

# --- Color palettes (7 values each, one per theme index) ---
# Hex primary (#33ccff family) — kitty cursor/border/tab/ANSI, tmux status
H_PRI=("#33ccff" "#ef596f" "#33ff55" "#ffdd00" "#ff8833" "#bd00ff" "#D7DAE0")
# Hex cyan variant (#00ffff family) — rofi foreground, waybar @teal, fastfetch
HC_PRI=("#00ffff" "#ef596f" "#33ff55" "#ffdd00" "#ff8833" "#bd00ff" "#D7DAE0")
# Hex secondary (#00ff99 family) — kitty selection_background, url_color
H_SEC=("#00ff99" "#d8985f" "#88ff44" "#ffee44" "#ffbb66" "#d65fff" "#B8BCC4")
# Hex dim (#00cccc family) — waybar @teal-dim, fastfetch separator
H_DIM=("#00cccc" "#c24038" "#33bb44" "#ccaa00" "#cc7722" "#9900cc" "#9DA5B4")
# rgba hex primary — hyprland active_border[0]
R_PRI=("rgba(33ccffee)" "rgba(ef596fee)" "rgba(33ff55ee)" "rgba(ffdd00ee)" "rgba(ff8833ee)" "rgba(bd00ffee)" "rgba(D7DAE0ee)")
# rgba hex secondary — hyprland active_border[1]
R_SEC=("rgba(00ff99ee)" "rgba(d8985fee)" "rgba(88ff44ee)" "rgba(ffee44ee)" "rgba(ffbb66ee)" "rgba(d65fffee)" "rgba(B8BCC4ee)")
# rgba hex dim — hyprland inactive_border
R_DIM=("rgba(00FFFFEE)" "rgba(c24038EE)" "rgba(33bb44EE)" "rgba(ccaa00EE)" "rgba(cc7722EE)" "rgba(9900ccEE)" "rgba(9DA5B4EE)")
# Decimal RGB triple — hyprlock + waybar hardcoded rgba (alpha preserved)
D_RGB=("0, 255, 255" "239, 89, 111" "51, 255, 85" "255, 221, 0" "255, 136, 51" "189, 0, 255" "215, 218, 224")
# Wallpaper filenames (in ~/.config/hypr/wallpapers/)
WP=(teal.jpg red.jpg green.jpg yellow.jpg orange.jpg purple.jpg white.jpg)

# --- Determine current and next theme ---
if [ -f "$THEME_FILE" ]; then
    CURRENT_THEME=$(cat "$THEME_FILE")
else
    CURRENT_THEME="teal"
fi

current_idx=${IDX[$CURRENT_THEME]:-0}

if [ "$1" = "--init" ]; then
    new_idx=$current_idx
    NEW_THEME=${THEMES[$new_idx]}
else
    new_idx=$(( (current_idx + 1) % ${#THEMES[@]} ))
    NEW_THEME=${THEMES[$new_idx]}
    echo "$NEW_THEME" > "$THEME_FILE"
fi

# --- Generate palette files ---
mkdir -p "$PALETTE_DIR"

# 1. Kitty colors (themed values only — constants stay in committed kitty.conf)
cat > "$PALETTE_DIR/kitty.conf" <<EOF
# Generated by toggle-theme.sh — do not edit manually (SUPER+SHIFT+R cycles themes).
selection_background    ${H_SEC[$new_idx]}
cursor                  ${H_PRI[$new_idx]}
url_color               ${H_SEC[$new_idx]}
active_border_color     ${H_PRI[$new_idx]}
active_tab_background   ${H_PRI[$new_idx]}
color4  ${H_PRI[$new_idx]}
color6  ${H_PRI[$new_idx]}
color12 ${H_PRI[$new_idx]}
color14 ${H_PRI[$new_idx]}
EOF

# 2. Tmux status bar
cat > "$PALETTE_DIR/tmux.conf" <<EOF
# Generated by toggle-theme.sh — do not edit manually.
set -g status-style "bg=black,fg=${H_PRI[$new_idx]}"
EOF

# 3. Waybar CSS (@define-color for teal + teal-dim, consumed by style.css)
cat > "$PALETTE_DIR/waybar.css" <<EOF
/* Generated by toggle-theme.sh — do not edit manually. */
@define-color teal ${HC_PRI[$new_idx]};
@define-color teal-dim ${H_DIM[$new_idx]};
EOF

# 4. Rofi rasi (themed values consumed by theme.rasi via ?import)
cat > "$PALETTE_DIR/rofi.rasi" <<EOF
/* Generated by toggle-theme.sh — do not edit manually. */
* {
    foreground: ${HC_PRI[$new_idx]};
    selected-background: ${HC_PRI[$new_idx]}33;
    selected-foreground: ${HC_PRI[$new_idx]};
    border-color: ${HC_PRI[$new_idx]};
}
EOF

# 5. Hyprland Lua palette (returned table, consumed by hyprland.lua via dofile)
cat > "$PALETTE_DIR/hyprland.lua" <<EOF
-- Generated by toggle-theme.sh — do not edit manually.
return {
    R_PRI = "${R_PRI[$new_idx]}",
    R_SEC = "${R_SEC[$new_idx]}",
    R_DIM = "${R_DIM[$new_idx]}",
}
EOF

# 6. Hyprlock palette ($accent variable, consumed by hyprlock.conf via source)
cat > "$PALETTE_DIR/hyprlock.conf" <<EOF
# Generated by toggle-theme.sh — do not edit manually.
\$accent = rgba(${D_RGB[$new_idx]}, 1.0)
EOF

# 7. Hyprpaper palette ($wallpaper variable, consumed by hyprpaper.conf via source)
cat > "$PALETTE_DIR/hyprpaper.conf" <<EOF
# Generated by toggle-theme.sh — do not edit manually.
\$wallpaper = $HOME/.config/hypr/wallpapers/${WP[$new_idx]}
EOF

# 8. Fastfetch palette file (sourced by ~/.zshrc.local)
cat > "$PALETTE_DIR/fastfetch-palette.sh" <<EOF
# Fastfetch color palette — rewritten by toggle-theme.sh on every theme switch.
# Sourced by ~/.zshrc.local. Do not edit manually; run SUPER+SHIFT+R instead.
FF_KEYS='${HC_PRI[$new_idx]}'
FF_TITLE='${HC_PRI[$new_idx]}'
FF_SEP='${H_DIM[$new_idx]}'
FF_LOGO='${HC_PRI[$new_idx]}'
EOF

# --- Reload signals ---
hyprctl reload >/dev/null 2>&1
pkill -SIGUSR2 waybar 2>/dev/null
kill -SIGUSR1 $(pgrep kitty) 2>/dev/null
tmux source-file "$HOME/.tmux.conf" 2>/dev/null

# On --init (first boot), hyprpaper was just launched by autostart — don't
# kill/restart it. On a real toggle, restart it to pick up the new wallpaper.
if [ "$1" != "--init" ]; then
    pkill hyprpaper 2>/dev/null; hyprpaper >/dev/null 2>&1 &
    notify-send "Theme Changed" "Switched to $NEW_THEME theme" -i preferences-desktop-theme 2>/dev/null
fi
